-- ── מיקום צומת הכניסה על לוח המסע ──────────────────────────────────────────
--
-- לכל שלב במסע יש pos_x/pos_y מאז 0019, אבל לצומת "נכנסים למסע" אין — הוא
-- אינו שורה ב-journey_steps אלא צומת וירטואלי שהלוח מצייר מתוך journeys.
-- התוצאה: אפשר היה לגרור כל כרטיסייה חוץ מזו שהמסע מתחיל בה.
--
-- הפתרון הראשון היה localStorage. הוא עבד, אבל המיקום היה של הדפדפן ולא של
-- המסע: אותו לוח נפתח במחשב אחר וחזר לברירת המחדל. מיקום הוא תכונה של הלוח
-- ולא של מי שמסתכל עליו, ולכן מקומו כאן.
--
-- ── למה שתי עמודות ולא jsonb ──
-- entry_value כבר קיים ב-journeys והוא jsonb, אבל יש לו משמעות: מנוע
-- האוטומציה קורא ממנו את הטריגר. דחיפת מיקום לתוכו הייתה מערבבת נתון תצוגה
-- בנתון התנהגות, ומזמינה את היום שבו שינוי בתצוגה שובר טריגר.
--
-- ── null ולא 0 ──
-- null אומר "לא נגרר מעולם", והלוח מציב את הכניסה בעוגן שלו — הקצה הימני,
-- כי בעברית המסע מתחיל שם. 0 היה אומר "נגרר לפינה השמאלית העליונה", וזה
-- מיקום אחר לגמרי.
--
-- הרצה: Supabase SQL editor, אחרי 0030_webhook_inbox.sql.

alter table journeys
  add column if not exists entry_pos_x integer,
  add column if not exists entry_pos_y integer;

comment on column journeys.entry_pos_x is
  'מיקום צומת הכניסה על הלוח. null = לא נגרר, והלוח מציב אותו בעוגן הימני.';
comment on column journeys.entry_pos_y is
  'ראו entry_pos_x.';
