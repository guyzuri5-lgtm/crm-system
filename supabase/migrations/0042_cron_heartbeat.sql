-- ── דופק המתזמן ─────────────────────────────────────────────────────────────
--
-- עד כה לא הייתה במערכת שום רשומה שאומרת "הקרון רץ". status-row.tsx כתב את
-- זה במפורש בהערה שלו — "המתזמן היה אמור לשבת כאן, אבל אין טבלה שרושמת את
-- ריצות הקרון" — והכרטיס של הקורסים נכנס למקומו.
--
-- ב-25.9.2026 המחיר של החסר הזה נגבה: GitHub Actions ירד מ-96 ריצות ביום
-- לשש, ההתדרדרות רצה יומיים בשקט גמור, ולקוחה ששילמה על קורס היא זו שגילתה
-- אותה. שום מסך במערכת לא יכול היה להראות זאת, כי לא היה ממה.
--
-- ── למה שורה אחת ולא יומן ריצות ──
-- השאלה היחידה שנשאלת בפועל היא "מתי רץ לאחרונה". יומן מלא היה גדל בלי
-- הגבלה (96 שורות ביום), היה דורש מחיקה תקופתית — שגם היא תלויה בקרון —
-- ולא היה עונה על שום שאלה נוספת. אם אי-פעם יידרש יומן, הוא ייבנה לצדו.
--
-- ── למה שתי חותמות ולא אחת ──
-- started ו-finished נפרדות כדי שריצה שנקטעה באמצע תיראה שונה מריצה שלא
-- התחילה. השתיים נכשלות באופן שונה לגמרי: הראשונה היא פונקציה שנחתכה
-- בתקרת הזמן, השנייה היא מתזמן שישן. מחוון שמציג אותן זהות אינו עוזר.

create table if not exists cron_heartbeat (
  -- שורה אחת בלבד, לנצח. ה-check על המפתח הוא מה שאוכף את זה — אותו דפוס
  -- בדיוק כמו ב-whatsapp_settings ו-booking_settings.
  id boolean primary key default true check (id),
  last_started_at  timestamptz,
  last_finished_at timestamptz,
  -- הסיכום המלא של הריצה האחרונה, כפי שה-endpoint מחזיר אותו. לא נקרא
  -- באף מסך כרגע, וקיים כדי שכשמשהו ייראה מוזר תהיה תשובה בלי לחפור בלוגים
  -- של Vercel — שממילא נשמרים שעה אחת בתוכנית Hobby.
  last_summary jsonb,
  -- ריק כשהריצה האחרונה הצליחה. ריצה שזרקה משאירה כאן את הסיבה, וזה מבדיל
  -- בין "לא רץ" לבין "רץ ונפל" — שני מצבים שנראים זהים מבחוץ.
  last_error text
);

comment on table cron_heartbeat is
  'שורה אחת שרושמת מתי ריצת הקרון האחרונה התחילה והסתיימה. המקור היחיד למחוון "המתזמן" בדף הבית.';

-- השורה נוצרת כאן ולא בקוד: הקוד מעדכן בלבד, ולכן אין בו מסלול שני של
-- "אולי אין שורה" שצריך להיות נכון גם הוא.
insert into cron_heartbeat (id) values (true) on conflict (id) do nothing;
