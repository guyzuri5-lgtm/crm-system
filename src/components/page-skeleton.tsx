import type { ReactNode } from "react";
import { SkelLine } from "@/components/skeleton";

/**
 * המסגרת של מסך בטעינה — כותרת אמיתית, תוכן משוער.
 *
 * ── למה הכותרת אמיתית ──
 * כותרת המסך ידועה עוד לפני שנשלפה שורה אחת מהמסד; היא כתובה בקוד. הצגת פס
 * אפור במקומה מחביאה מידע שכבר קיים, ובלחיצה על "כל הקורסים" זו ההוכחה
 * הראשונה שהלחיצה נקלטה. לכן `loading.tsx` של כל מסך מעביר את הכותרת שלו
 * לכאן, והשלד חל על התוכן בלבד.
 *
 * המחיר: הכותרת כתובה בשני מקומות — בעמוד ובשלד שלו. כותרת שתשתנה באחד ולא
 * בשני תבהב לרגע בנוסח הישן ותתוקן. זה קוסמטי ורגעי, וזה שווה את המשוב
 * המיידי.
 */
export function PageSkeleton({
  title,
  children,
}: {
  /** כותרת המסך כלשונה. כשאינה ידועה מראש (שם של איש קשר) — פס במקומה. */
  title?: string;
  children: ReactNode;
}) {
  return (
    <div className="flex flex-col gap-5">
      {/* אותו מרקאפ בדיוק כמו בעמודים עצמם — h-page > div > h1 + p — כדי
          שהכותרת לא תזוז כשהתוכן האמיתי מחליף את השלד. ה-<p> נשאר <p> ולא
          הופך ל-div: הריווח והרוחב המרבי שלו מגיעים מ-.h-page p. */}
      <div className="h-page">
        <div>
          {title ? <h1>{title}</h1> : <SkelLine w="220px" h={21} />}
          <p>
            <SkelLine w="min(420px, 70%)" h={12} />
          </p>
        </div>
      </div>
      {children}
    </div>
  );
}
